                            "set_standard_analog_out(0,read_float_register(13))\n"
                            "end\n";

string read_laser_power = "function read_laser_power()\n"
                           "laser_power=read_float_register(13)\n"
                           "laser_power=ceil(3000*laser_power/10)\n"
                           "write_int16_register(72,laser_power)\n"
                           "end\n";

