string swap_bytes_for_word = "function swap_bytes_for_word(data4)\n"
                              "------若数值小于0，则转换为无符号数计算--------\n"
                              "if(data4<0) then\n"
                              "data4=65536+data4\n"
                              "end\n"
                              "data_4={}\n"
                              "------提取数据1第1位参数-------\n"
                              "data_4[1]=data4//(16^3)\n"
                              "------提取数据1第2位参数-------\n"
                              "data_4[2]=(data4-data_4[1]*(16^3))//(16^2)\n"
                              "------提取数据2第3位参数-------\n"
                              "data_4[3]=(data4-data_4[1]*(16^3)-data_4[2]*(16^2))//16\n"
                              "------提取数据2第4位参数-------\n"
                              "data_4[4]=data4%16\n"
                              "------将数据第1位、第2位和第3位、第4位互换整合为1个新的数据---------\n"
                              "result1=(data_4[3]*(16^3))+(data_4[4]*(16^2))+(data_4[1]*16+data_4[2])\n"
                              "return result1			------返回结果\n"
                              "end\n";

