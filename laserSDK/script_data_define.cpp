string Lua_crc16 = "function Lua_crc16(data)\n"
                    "\ttmp=0xFFFF\n"
                    "\tfor i=1,6,1 do\n"
                    "\t\ttmp=(data[i])~tmp\n"
                    "\t\tfor j=1,8,1 do\n"
                    "\t\t\tif(tmp&1==1) then\n"
                    "\t\t\t\ttmp=tmp>>1 \n"
                    "\t\t\t\ttmp=40961~tmp\n"
                    "\t\t\telse\n"
                    "\t\t\t\ttmp=tmp>>1\n"
                    "\t\t\tend\n"
                    "\t\tend\n"
                    "\tend\n"
                    "\treturn tmp\n"
                    "end\n";

